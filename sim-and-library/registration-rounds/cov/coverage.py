#!/usr/bin/env python3
"""cov/coverage.py (10-20, spec §4.102 item 4): empirical coverage of the deviation margin lambda_l * sigma_hat_l.
Read-only use of the frozen qsim code: sigma_hat comes from v8sim2.Prior built on prior_traces.json with
v8sim7.cfg_measured() (the configuration v8sim10.sim_nest2 / the daemon use), kind "win" (replenishment).

Rise definition = exactly Prior's "win" sample (v8sim2.py:39-42; same as export_sigma.py -> daemon prior_sigma.json):
    R(t) = max(0, max_{tau in [h0, h0+g]} D(t+tau) - D(t)),  g = TICK = 30 s,
    h0 = h_UP = 30 s (UP), h_VY = 150 s (VY), h_WK + h_UP = 150 s (WK); i.e. the arrival window [H-g, H] of the
    replenish horizon H = cfg.win = 60 / 180 / 180 s. This is NOT the max over (0, H] (that is Prior's "run" kind);
    the full-horizon max (0, H] is reported as a secondary, stricter column.
Margin  M(t) = lambda_l * Prior.sigma("win", l, D(t)) (bucket 10 UE, linear interpolation between bucket centres).
Units: UE (40-UE scale). The daemon multiplies both D and sigma by ue_pps = 250 kpps; R > M is invariant to that factor.
Evaluation points: each minute start t = 0..59 min whose arrival window lies inside the 60-min trace
(primary, as requested), and every 30-s planner tick (the exact sample set Prior was fitted on; secondary).
In-sample: sigma_hat is fitted on the same 1615 traces.
Usage: nice -n 19 taskset -c 13,14 python3 cov/coverage.py   (from experiment/qsim)"""
import json, math, sys, os
import numpy as np
HERE=os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, os.path.dirname(HERE))
import v8sim2 as S, v8sim7 as M
lib=M.lib; cfg=M.cfg_measured(); pr=S.Prior(lib,cfg)
DT=S.DT; G=S.TICK
SETS={"S4a":dict(vm=2.83,up=3.08),"S4b":dict(vm=1.83,up=2.00)}
H0={"up":cfg.h["up"],"vy":cfg.h["vy"],"wk":cfg.h["wk"]+cfg.h["up"]}   # start of arrival window (s)
HW={k:H0[k]+G for k in H0}                                           # = cfg.win (replenish horizon H_l)
assert HW==cfg.win, (HW,cfg.win)
# rows: (label, layer whose sigma table is used, which lambda)
ROWS=[("UP","up","up"),("VY","vy","vm"),("WK","wk","vm"),("WK-slotpath","wk","up")]
BK=[(0,9),(10,19),(20,29),(30,40)]
def bucket(D): return 0 if D<10 else (1 if D<20 else (2 if D<30 else 3))
Phi=lambda x: 0.5*(1+math.erf(x/math.sqrt(2)))
def collect(step):
    """returns per row: arrays D, R_win, R_full, sigma"""
    out={}
    for lab,k,_ in ROWS:
        k0=H0[k]//DT; k1=HW[k]//DT; Ds=[];Rw=[];Rf=[];Sg=[]
        for tr in lib:
            d=S.expand(tr["ue"])*cfg.scale; n=len(d)
            for i in range(0,n,step):
                if i+k1>n-1: break          # full arrival window inside the trace (same bound as Prior)
                D=d[i]; Ds.append(D)
                Rw.append(max(0.0,d[i+k0:i+k1+1].max()-D))
                Rf.append(max(0.0,d[i+1:i+k1+1].max()-D))
                Sg.append(pr.sigma("win",k,D))
        out[lab]=tuple(np.array(x) for x in (Ds,Rw,Rf,Sg))
    return out
if __name__=="__main__":
    minute=collect(60//DT); tick=collect(G//DT)
    # buckets loop helper: j<4 regular, j==4 all
    BK=[(0,9),(10,19),(20,29),(30,40)]
    def table2(data):
        res={}
        for sname,lam in SETS.items():
            for lab,k,lk in ROWS:
                L=lam[lk]; Ds,Rw,Rf,Sg=data[lab]; Mg=L*Sg; b=np.array([bucket(x) for x in Ds]); cell={}
                for j in range(5):
                    m=(b==j) if j<4 else np.ones(len(Ds),bool); n=int(m.sum())
                    key="all" if j==4 else f"{BK[j][0]}-{BK[j][1]}"
                    cell[key]=dict(n=n,
                        exceed_win=float((Rw[m]>Mg[m]).mean()) if n else None,
                        exceed_full=float((Rf[m]>Mg[m]).mean()) if n else None,
                        k_exceed_win=int((Rw[m]>Mg[m]).sum()),
                        sigma_mean_ue=float(Sg[m].mean()) if n else None,
                        margin_mean_ue=float(Mg[m].mean()) if n else None,
                        zero_rise_frac=float((Rw[m]==0).mean()) if n else None)
                res[f"{sname}/{lab}"]=dict(lam=L,lam_kind=("lambda_VM" if lk=="vm" else "lambda_UP"),sigma_table=k,
                    H_sec=HW[k],arrival_window_sec=[H0[k],HW[k]],gauss_1mPhi=1-Phi(L),cells=cell)
        return res
    out=dict(definition=__doc__.split("Usage")[0],n_traces=len(lib),cfg_h=cfg.h,cfg_win=cfg.win,
             sigma_buckets={k:{kk:v for kk,v in pr.sig[("win",k)].items()} for k in cfg.h},
             sigma_all={k:pr.sig[("win",k,"all")] for k in cfg.h},
             per_minute=table2(minute),per_tick=table2(tick))
    json.dump(out,open(os.path.join(HERE,"coverage.json"),"w"),indent=1,default=float)
    # markdown
    L=[]; P=lambda s="":L.append(s)
    P("# Empirical coverage of the deviation margin λ_l·σ̂_l (spec §4.102 item 4)")
    P(); P("Generated by `experiment/qsim/cov/coverage.py` (read-only use of frozen `v8sim2.Prior`, `v8sim7.cfg_measured`); raw numbers in `coverage.json`.")
    P(); P("**Definition (same as the planner's σ̂, `v8sim2.py:39-42`, `export_sigma.py:15-18` → daemon `prior_sigma.json`).** "
           "Rise R(t) = max(0, max_{τ∈[H_l−30 s, H_l]} D(t+τ) − D(t)): the peak over the *arrival window* (last 30-s tick) of the replenish horizon, "
           f"not the max over (0, H_l] and not the endpoint. H_UP = {HW['up']} s (window [{H0['up']},{HW['up']}] s), H_VY = {HW['vy']} s ([{H0['vy']},{HW['vy']}]), "
           f"H_WK = {HW['wk']} s ([{H0['wk']},{HW['wk']}] = h_WK+h_UP+g). Margin M = λ·σ̂_win,l(D(t)), σ̂ = population std of R in 10-UE buckets of D(t) (≥30 samples, else global), "
           "linearly interpolated between bucket centres. Units UE (×250 kpps in the daemon; ratio-invariant). "
           "Exceed = R > M. In-sample (σ̂ fitted on the same 1615 traces). σ̂ is the std of a non-negative, mostly-zero variable taken about its mean, "
           "while the margin is measured from zero, so 1−Φ(λ) is only a nominal reference.")
    P(); P("Rows: UP uses λ_UP; VY and WK use λ_VM (same λ, same H = 180 s but different σ̂ tables because WK's window starts at h_WK+h_UP=150 s and VY's at h_VY=150 s — identical windows here, so VY and WK coincide). "
           "`WK-slotpath` = the second term of the worker target, need_UP(D + λ_UP·σ̂_win,WK)/spw (`v8sim10.py:27`).")
    for name,key in (("Per minute start (primary; t = whole minutes with the arrival window inside the 60-min trace)","per_minute"),
                     ("Per 30-s planner tick (secondary; exactly Prior's sample set)","per_tick")):
        P(); P(f"## {name}")
        for sname in SETS:
            P(); P(f"### {sname} (λ_VM {SETS[sname]['vm']}, λ_UP {SETS[sname]['up']})")
            P(); P("| layer | λ | 1−Φ(λ) | 0–9 UE | 10–19 | 20–29 | 30–40 | all | all, full-horizon max (0,H] |")
            P("|---|---|---|---|---|---|---|---|---|")
            for lab,_,_ in ROWS:
                r=out[key][f"{sname}/{lab}"]; c=r["cells"]
                f=lambda x: f"{100*x['exceed_win']:.2f}% (n={x['n']})" if x['n'] else "— (n=0)"
                P(f"| {lab} | {r['lam']} | {100*r['gauss_1mPhi']:.2f}% | "+" | ".join(f(c[b]) for b in ("0-9","10-19","20-29","30-40","all"))+f" | {100*c['all']['exceed_full']:.2f}% |")
    P(); P("## σ̂_win per bucket (UE; bucket b = D//10; bucket 4 = D=40 only)")
    P(); P("| layer | "+" | ".join(f"b{b}" for b in range(5))+" | global |"); P("|---|---|---|---|---|---|---|")
    for k in ("up","vy","wk"):
        t=pr.sig[("win",k)]; P(f"| {k.upper()} | "+" | ".join(("—" if t.get(b) is None else f"{t[b]:.3f}") for b in range(5))+f" | {pr.sig[('win',k,'all')]:.3f} |")
    P(); P("Cross-check: these σ̂ values equal the daemon's `hhro-daemon/internal/hbo/prior_sigma.json` win[60] and win[180] tables (all, b0..b4, n = 190570 / 184110) to full precision.")
    P(); P("## Reading")
    P(); P("- Empirical exceedance is roughly 10–37× the Gaussian nominal 1−Φ(λ) at S4a and 3.5–6× at S4b (per cell): the rise distribution is a point mass at 0 plus a heavy right tail, so λ·σ̂ is not a quantile. Hence the wording \"deviation multiplier with empirically reported coverage\".")
    P("- Margin exceedance is per decision point and is not the SLO risk the λ were calibrated to (0.5% / 2% of minutes in loss): need_l(·) rounds up to whole units, so a rise beyond the margin only costs SLO when it also crosses the next unit boundary before replenishment lands.")
    P("- 30–40 UE has the lowest exceedance because demand is capped at 40 UE (σ̂ of bucket 4 = 0 and interpolation shrinks σ̂ toward it above 35 UE, but rises there are also bounded). 20–29 UE is the worst bucket in every row.")
    P("- VY and WK rows coincide: both arrival windows are [150,180] s (h_VY = 150; h_WK + h_UP = 120 + 30), so their σ̂ tables are identical and they share λ_VM.")
    open(os.path.join(HERE,"coverage_table.md"),"w").write("\n".join(L)+"\n")
    print("\n".join(L))
